#!/usr/bin/env python3
"""Processing-in-Memory (PIM) timing sensitivity report.

One host timing value at a time is raised by 25% (rounded up) in the
analytic model of ``pim_timing.py``, on the committed tables
``timing_<std>.json``; the PIM parameters that default to it follow. The
report gives the change of the unloaded latency U in percent for six
requests, and leaves out values that move none of them by 1% or more.
It runs the model only, no simulator.

Examples::

    libpim/timing/sweep.py              # print the report
    libpim/timing/sweep.py --write      # libpim/timing/sensitivity.md
    libpim/timing/sweep.py --check      # exit 1 if it is out of date
"""

import argparse
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import pim_timing as pt  # noqa: E402

REPORT = os.path.join(HERE, "sensitivity.md")
RAISE = 1.25
THRESHOLD = 1.0  # percent, after rounding to one decimal

# The report's requests: (heading, class, mode, columns or "row").
COLUMNS = (
    ("AB row Baseline", "ab_rd", "baseline", "row"),
    ("AB row Ideal", "ab_rd", "ideal", "row"),
    ("AB 1 Baseline", "ab_rd", "baseline", 1),
    ("SB RD row", "sb_rd", None, "row"),
    ("SB WR row", "sb_wr", None, "row"),
    ("NB load 1", "gb_rd", None, 1),
)

# Model terms that only the host closed forms read (no PIM request).
HOST_ONLY_TERMS = ("rp", "rfc", "unit", "sync")


def swept(t):
    """The host values the model of t reads: its per-standard terms and
    every name in the PIM default rules and the read latency, in the
    table's order."""
    names = set()
    for term, name in pt.FAMILY[t["standard"]].items():
        if term not in HOST_ONLY_TERMS and name:
            names.add(name)
    rules = [e["rule"] for e in t["pim"].values()]
    rules.append(t["read_latency"]["rule"])
    for r in rules:
        names.update(re.findall(r"[A-Za-z_]\w*", r))
    return [k for k in t["host"] if k in names]


def latencies(t):
    cols = t["geometry"]["cols_per_row"]
    return [
        pt.unloaded(t, cls, mode, cols if n == "row" else n)
        for _, cls, mode, n in COLUMNS
    ]


def raised(value):
    up = -(-value * 5 // 4)
    return up if up > value else value + 1


def sweep(std):
    """[(name, value, raised, [percent per column])] for every swept host
    value of std, and the base latencies."""
    t = pt.load(std)
    base = latencies(t)
    rows = []
    for name in swept(t):
        v = t["host"][name]
        up = raised(v)
        u = latencies(pt.with_values(t, host={name: up}))
        pct = [round(100 * (a / b - 1), 1) for a, b in zip(u, base)]
        rows.append((name, v, up, pct))
    return rows, base


def _cell(p):
    return "0" if p == 0 else f"{p:+.1f}"


def report():
    head = "| Standard | Value (now → +25%) | " + " | ".join(
        c[0] for c in COLUMNS
    )
    lines = [
        "# PIM timing sensitivity",
        "",
        "Generated by `libpim/timing/sweep.py` from the committed "
        "`timing_<std>.json`; do not edit.",
        "",
        "Processing-in-Memory (PIM) unloaded latency U",
        "when one host timing value is raised by 25% (rounded up), the PIM",
        "defaults following it: change in percent. Requests:",
        "all-bank (AB) multiply-accumulate (MAC) of a full row in Baseline",
        "and in Ideal mode and of one column in Baseline, a single-bank (SB)",
        "read-class and write-class request of a full row, and a non-bank",
        "(NB) load of one column. Every host value the model reads is swept;",
        f"values that move no request by {THRESHOLD:.0f}% or more are left out.",
        "",
        "Base U in clocks:",
        "",
        "| Standard | " + " | ".join(c[0] for c in COLUMNS) + " |",
        "|---|" + "---|" * len(COLUMNS),
    ]
    results = {std: sweep(std) for std in pt.STANDARDS}
    for std, (_, base) in results.items():
        lines.append(f"| {std} | " + " | ".join(str(b) for b in base) + " |")
    lines += ["", head + " |", "|---|---|" + "---|" * len(COLUMNS)]
    for std, (rows, _) in results.items():
        for name, v, up, pct in rows:
            if max(abs(p) for p in pct) < THRESHOLD:
                continue
            cells = " | ".join(_cell(p) for p in pct)
            lines.append(f"| {std} | `{name}` {v} → {up} | {cells} |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help="write the report")
    g.add_argument(
        "--check", action="store_true", help="exit 1 if it is out of date"
    )
    args = ap.parse_args(argv)
    text = report()
    if args.write:
        with open(REPORT, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(REPORT)}")
        return 0
    if args.check:
        try:
            with open(REPORT) as f:
                ok = f.read() == text
        except OSError:
            ok = False
        print(
            "sensitivity report up to date"
            if ok
            else f"{os.path.relpath(REPORT)} is out of date"
        )
        return 0 if ok else 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
